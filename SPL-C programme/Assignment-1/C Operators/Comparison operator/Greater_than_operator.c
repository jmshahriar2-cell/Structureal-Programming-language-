#include <stdio.h>

int main() {
    // Declare and initialize integer variables x and y for comparison
    int x = 5; 
    int y = 3; 

    // Use the greater than operator (>) to compare x and y
    // In C, comparisons return 1 for true and 0 for false
    printf("%d\n", x > y); // returns 1 (true) because 5 is greater than 3

    return 0; // Signals successful program termination
}